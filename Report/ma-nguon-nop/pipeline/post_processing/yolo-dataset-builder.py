#!/usr/bin/env python3
"""
YOLO Dataset Builder

Builds YOLO format dataset from synthetic images + masks.
Creates train/val/test directories with images/ and labels/ subdirectories.
Generates data.yaml configuration file for Ultralytics YOLO training.
"""

import os
import shutil
from pathlib import Path
from typing import Dict, List
from tqdm import tqdm

# Import directly from module file to avoid circular import
from importlib import import_module
mask_to_annotation = import_module('.mask-to-annotation-converter', package='post_processing')


# Category mapping: defect_type -> category_id (1-indexed, will be 0-indexed for YOLO)
CATEGORY_MAP = {
    "crack": 1,
    "porosity": 2,
    "inclusion": 3,
    "lack_of_fusion": 4,
    "undercut": 5
}

CATEGORY_NAMES = ["crack", "porosity", "inclusion", "lack_of_fusion", "undercut"]


def build_yolo_dataset(
    image_mask_pairs: List[Dict],
    split_name: str,
    output_dir: Path
) -> int:
    """
    Build YOLO format dataset for a specific split.

    Args:
        image_mask_pairs: List of dicts with keys:
            - image_path: Path to synthetic image
            - mask_path: Path to binary mask
            - defect_type: Defect category name
        split_name: 'train', 'val', or 'test'
        output_dir: Root YOLO dataset directory

    Returns:
        Number of images processed
    """
    # Create directory structure: yolo/{split}/images and yolo/{split}/labels
    split_dir = output_dir / split_name
    images_dir = split_dir / "images"
    labels_dir = split_dir / "labels"

    images_dir.mkdir(parents=True, exist_ok=True)
    labels_dir.mkdir(parents=True, exist_ok=True)

    processed_count = 0

    for item in tqdm(image_mask_pairs, desc=f"Building YOLO {split_name}"):
        img_path = item["image_path"]
        mask_path = item["mask_path"]
        defect_type = item["defect_type"]

        img_basename = os.path.basename(img_path)
        img_name_no_ext = os.path.splitext(img_basename)[0]

        # Copy image to split/images/
        dest_img_path = images_dir / img_basename
        shutil.copy2(img_path, dest_img_path)

        # Convert mask to YOLO label format
        try:
            ann = mask_to_annotation.mask_to_annotation(
                str(mask_path),
                defect_type,
                CATEGORY_MAP,
                format="yolo"
            )

            if ann is None:
                print(f"Warning: Empty mask for {img_basename}, creating empty label")
                label_content = ""
            else:
                class_id = ann["class_id"]
                bbox = ann["bbox"]  # [x_center, y_center, width, height] normalized
                label_content = f"{class_id} {bbox[0]:.6f} {bbox[1]:.6f} {bbox[2]:.6f} {bbox[3]:.6f}\n"

            # Write label file
            label_path = labels_dir / f"{img_name_no_ext}.txt"
            with open(label_path, 'w') as f:
                f.write(label_content)

            processed_count += 1

        except Exception as e:
            print(f"Error processing {img_basename}: {e}")
            continue

    print(f"✓ Built YOLO {split_name}: {processed_count} images")
    return processed_count


def create_yolo_data_yaml(output_dir: Path, dataset_name: str = "xray_defects"):
    """
    Create data.yaml configuration file for YOLO training.

    Args:
        output_dir: Root YOLO dataset directory
        dataset_name: Dataset name for reference
    """
    # Use absolute path for YOLO training
    abs_path = output_dir.resolve()

    yaml_content = f"""# YOLO Dataset Configuration - The Data Mint Synthetic X-ray Defects
# Auto-generated by post-processing pipeline

path: {abs_path}
train: train/images
val: val/images
test: test/images

# Number of classes
nc: 5

# Class names (0-indexed)
names:
  0: crack
  1: porosity
  2: inclusion
  3: lack_of_fusion
  4: undercut
"""

    yaml_path = output_dir / "data.yaml"
    with open(yaml_path, 'w') as f:
        f.write(yaml_content)

    print(f"✓ Created data.yaml: {yaml_path}")


def validate_yolo_format(yolo_dir: Path) -> bool:
    """
    Validate YOLO dataset structure and format.

    Args:
        yolo_dir: Root YOLO dataset directory

    Returns:
        True if valid, False otherwise
    """
    required_splits = ["train", "val"]

    for split in required_splits:
        images_dir = yolo_dir / split / "images"
        labels_dir = yolo_dir / split / "labels"

        if not images_dir.exists():
            print(f"✗ Missing directory: {images_dir}")
            return False

        if not labels_dir.exists():
            print(f"✗ Missing directory: {labels_dir}")
            return False

        # Check that each image has a corresponding label
        images = list(images_dir.glob("*.png")) + list(images_dir.glob("*.jpg"))
        for img_path in images:
            label_path = labels_dir / f"{img_path.stem}.txt"
            if not label_path.exists():
                print(f"✗ Missing label: {label_path}")
                return False

    # Check data.yaml exists
    if not (yolo_dir / "data.yaml").exists():
        print(f"✗ Missing data.yaml")
        return False

    print(f"✓ YOLO validation passed: {yolo_dir}")
    return True
