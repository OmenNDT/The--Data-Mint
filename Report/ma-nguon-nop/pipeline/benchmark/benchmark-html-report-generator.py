"""
Generate HTML visual comparison report for benchmark evaluation.

Creates a grid: 5 defect types (rows) x 5 models (columns) with metrics overlay.

Usage:
    python3 pipeline/benchmark/benchmark-html-report-generator.py
"""

import json
import base64
import logging
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

PROJECT_ROOT = Path("/home/sontn/Projects/The Data Mint")
BENCHMARK_DIR = PROJECT_ROOT / "output" / "benchmark"
RESULTS_PATH = BENCHMARK_DIR / "evaluation-results.json"

ALL_MODELS = ["baseline", "medxray", "realvis", "absreal", "cyberreal"]
DEFECTS = ["crack", "porosity", "inclusion", "lack_of_fusion", "undercut"]

HTML_TEMPLATE = """<!DOCTYPE html>
<html><head>
<meta charset="utf-8">
<title>Benchmark Evaluation Report</title>
<style>
  body {{ font-family: sans-serif; margin: 20px; background: #1a1a1a; color: #eee; }}
  h1, h2 {{ color: #4fc3f7; }}
  table {{ border-collapse: collapse; margin: 20px 0; }}
  th, td {{ border: 1px solid #444; padding: 8px; text-align: center; }}
  th {{ background: #333; }}
  .rank-1 {{ background: #1b5e20; }}
  .rank-2 {{ background: #33691e; }}
  .grid-cell {{ position: relative; }}
  .grid-cell img {{ display: block; width: 200px; height: 200px; object-fit: cover; }}
  .metrics {{ font-size: 11px; background: rgba(0,0,0,0.7); padding: 4px; }}
  .winner {{ border: 3px solid #ffd600; }}
</style>
</head><body>
<h1>Base Model Benchmark — Evaluation Report</h1>

<h2>Composite Ranking</h2>
<table>
<tr><th>Rank</th><th>Model</th><th>Composite</th><th>FID ↓</th><th>FID norm</th><th>SSIM ↑</th><th>Sharpness norm</th></tr>
{ranking_rows}
</table>

<h2>Visual Comparison Grid</h2>
<table>
<tr><th>Defect</th>{model_headers}</tr>
{grid_rows}
</table>

<h2>Per-Defect SSIM</h2>
<table>
<tr><th>Defect</th>{model_headers}</tr>
{ssim_rows}
</table>

<h2>Per-Defect Sharpness</h2>
<table>
<tr><th>Defect</th>{model_headers}</tr>
{sharpness_rows}
</table>

<p><em>Generated by benchmark-html-report-generator.py</em></p>
</body></html>"""


def encode_image_base64(img_path: Path) -> str:
    """Read image and return base64-encoded string."""
    with open(img_path, "rb") as f:
        return base64.b64encode(f.read()).decode("ascii")


def find_first_image(directory: Path) -> Path | None:
    """Find first PNG image in directory."""
    images = sorted(directory.glob("*.png"))
    return images[0] if images else None


def generate_report():
    """Generate HTML report from evaluation results."""
    if not RESULTS_PATH.exists():
        logger.error(f"Results not found: {RESULTS_PATH}. Run evaluation pipeline first.")
        return

    with open(RESULTS_PATH) as f:
        results = json.load(f)

    # Filter to models that have results
    models = [m for m in ALL_MODELS if m in results]
    ranked = sorted(models, key=lambda m: results[m].get("composite", 0), reverse=True)

    # Ranking table
    ranking_rows = ""
    for m in ranked:
        r = results[m]
        rank = r.get("rank", "-")
        css = f' class="rank-{rank}"' if rank in (1, 2) else ""
        ranking_rows += (
            f"<tr{css}><td>{rank}</td><td><b>{m}</b></td>"
            f"<td>{r.get('composite', 0):.4f}</td>"
            f"<td>{r.get('fid', 0):.1f}</td>"
            f"<td>{r.get('fid_norm', 0):.4f}</td>"
            f"<td>{r.get('ssim_mean', 0):.4f}</td>"
            f"<td>{r.get('sharpness_norm', 0):.4f}</td></tr>\n"
        )

    model_headers = "".join(f"<th>{m}</th>" for m in models)

    # Visual grid
    grid_rows = ""
    for defect in DEFECTS:
        row = f"<td><b>{defect}</b></td>"
        for model in models:
            img_dir = BENCHMARK_DIR / model / defect
            img_path = find_first_image(img_dir)
            if img_path:
                b64 = encode_image_base64(img_path)
                ssim_val = results[model]["ssim"].get(defect, {}).get("mean", 0)
                sharp_val = results[model]["sharpness"].get(defect, {}).get("mean", 0)
                winner_css = " winner" if results[model].get("rank") == 1 else ""
                row += (
                    f'<td class="grid-cell{winner_css}">'
                    f'<img src="data:image/png;base64,{b64}"/>'
                    f'<div class="metrics">SSIM: {ssim_val:.3f} | Sharp: {sharp_val:.0f}</div>'
                    f"</td>"
                )
            else:
                row += "<td>No image</td>"
        grid_rows += f"<tr>{row}</tr>\n"

    # SSIM table
    ssim_rows = ""
    for defect in DEFECTS:
        row = f"<td>{defect}</td>"
        for model in models:
            val = results[model]["ssim"].get(defect, {}).get("mean", 0)
            row += f"<td>{val:.4f}</td>"
        ssim_rows += f"<tr>{row}</tr>\n"

    # Sharpness table
    sharpness_rows = ""
    for defect in DEFECTS:
        row = f"<td>{defect}</td>"
        for model in models:
            val = results[model]["sharpness"].get(defect, {}).get("mean", 0)
            row += f"<td>{val:.1f}</td>"
        sharpness_rows += f"<tr>{row}</tr>\n"

    html = HTML_TEMPLATE.format(
        ranking_rows=ranking_rows,
        model_headers=model_headers,
        grid_rows=grid_rows,
        ssim_rows=ssim_rows,
        sharpness_rows=sharpness_rows,
    )

    output_path = BENCHMARK_DIR / "evaluation-report.html"
    output_path.write_text(html)
    logger.info(f"Report saved: {output_path}")


if __name__ == "__main__":
    generate_report()
